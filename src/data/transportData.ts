export function calculateTransportFareEstimate(
  vehicle: TransportVehicleConfig,
  distanceKm: number,
  helperCount: 0 | 1 | 2 = 0,
  isUrgent: boolean = false
): {
  baseFare: number;
  distanceFare: number;
  helperFee: number;
  urgentFee: number;
  estimatedFareMin: number;
  estimatedFareMax: number;
} {
  const baseFare = vehicle.baseFare;
  const distanceFare = Math.round(distanceKm * vehicle.perKmRate);
  const helperFee = helperCount === 1 ? 150 : helperCount === 2 ? 300 : 0;
  const urgentFee = isUrgent ? 60 : 0;

  const totalCalculated = Math.max(vehicle.minFare, baseFare + distanceFare + helperFee + urgentFee);
  const estimatedFareMin = Math.round(totalCalculated * 0.95);
  const estimatedFareMax = Math.round(totalCalculated * 1.15);

  return {
    baseFare,
    distanceFare,
    helperFee,
    urgentFee,
    estimatedFareMin,
    estimatedFareMax,
  };
}
